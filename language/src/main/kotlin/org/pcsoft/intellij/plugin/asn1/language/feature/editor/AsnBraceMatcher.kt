package org.pcsoft.intellij.plugin.asn1.language.feature.editor

import com.intellij.lang.BracePair
import com.intellij.lang.PairedBraceMatcher
import com.intellij.psi.PsiFile
import com.intellij.psi.tree.IElementType
import org.pcsoft.intellij.plugin.asn1.language.parser.psi.AsnTypes

/**
 * Matches `{` with `}` and `(` with `)`. Missing or surplus braces are no problem, they simply have no partner.
 */
class AsnBraceMatcher : PairedBraceMatcher {
    override fun getPairs(): Array<BracePair> = PAIRS

    override fun isPairedBracesAllowedBeforeType(lbraceType: IElementType, contextType: IElementType?): Boolean = true

    override fun getCodeConstructStart(file: PsiFile?, openingBraceOffset: Int): Int = openingBraceOffset

    private companion object {
        val PAIRS: Array<BracePair> = arrayOf(
            BracePair(AsnTypes.LBRACE, AsnTypes.RBRACE, true),
            BracePair(AsnTypes.LPAREN, AsnTypes.RPAREN, true),
        )
    }
}
